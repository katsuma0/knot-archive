// build-sw.mjs: list every static file into sw-assets.js with a content hash,
// so the service worker precaches the whole app and refreshes when anything changes.
import { readdirSync, statSync, readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { resolve, relative, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const include = ['index.html', 'styles.css', 'manifest.webmanifest', 'src', 'icons'];
const files = [];
function walk(p) {
  const st = statSync(p);
  if (st.isDirectory()) { for (const f of readdirSync(p)) walk(resolve(p, f)); return; }
  const rel = relative(root, p).split('\\').join('/');
  if (rel.startsWith('src/knots/_') && !rel.endsWith('_lib.js')) return;
  files.push(rel);
}
for (const i of include) walk(resolve(root, i));
files.sort();
const hash = createHash('sha256');
for (const f of files) hash.update(f).update(readFileSync(resolve(root, f)));
const version = hash.digest('hex').slice(0, 12);
const assets = ['./', ...files];
writeFileSync(resolve(root, 'sw-assets.js'), `// generated by tools/build-sw.mjs\nself.ASSET_VERSION = '${version}';\nself.ASSETS = ${JSON.stringify(assets, null, 0)};\n`);
console.log(`sw-assets.js: ${files.length} files, version ${version}`);
