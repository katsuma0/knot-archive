// gen-index.mjs: rebuild src/knots/index.js from the knot files on disk.
// Knots are grouped by category (order from src/data.js) and, inside a
// category, by the ORDER list below (the ones a beginner needs first), then
// alphabetically. Run it after adding or removing a knot file.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dir = resolve(root, 'src/knots');
const CATS = ['stoppers', 'loops', 'hitches', 'bends', 'binding', 'friction', 'lashings', 'fishing', 'rope-care'];
const ORDER = [
  'overhand', 'figure-eight', 'double-overhand', 'ashleys-stopper',
  'bowline', 'figure-eight-on-a-bight', 'figure-eight-follow-through', 'alpine-butterfly', 'slip-knot', 'overhand-loop', 'yosemite-bowline', 'running-bowline', 'bowline-on-a-bight', 'inline-figure-eight',
  'clove-hitch', 'two-half-hitches', 'round-turn-two-half-hitches', 'taut-line-hitch', 'truckers-hitch', 'siberian-hitch', 'girth-hitch', 'timber-hitch', 'marlinspike-hitch', 'buntline-hitch', 'anchor-hitch', 'highwaymans-hitch', 'tensionless-hitch', 'rolling-hitch', 'pile-hitch', 'farrimond-friction-hitch', 'clove-hitch-loops',
  'sheet-bend', 'double-sheet-bend', 'double-fishermans', 'figure-eight-bend', 'water-knot', 'flat-overhand-bend', 'zeppelin-bend', 'carrick-bend',
  'square-knot', 'surgeons-knot', 'constrictor-knot', 'packers-knot', 'transom-knot',
  'prusik', 'klemheist', 'autoblock', 'munter-hitch', 'munter-mule', 'bachmann',
  'square-lashing', 'diagonal-lashing', 'shear-lashing', 'tripod-lashing',
  'improved-clinch', 'palomar', 'uni-knot', 'blood-knot', 'surgeons-loop', 'perfection-loop', 'arbor-knot',
  'alpine-coil', 'butterfly-coil', 'daisy-chain', 'common-whipping',
];
const only = new Set(process.argv.slice(2));
const knots = [];
for (const f of readdirSync(dir)) {
  if (!f.endsWith('.js') || f.startsWith('_') || f === 'index.js') continue;
  const id = f.slice(0, -3);
  if (only.size && !only.has(id)) continue;
  const src = readFileSync(resolve(dir, f), 'utf8');
  const cat = (src.match(/category:\s*'([\w-]+)'/) || [])[1];
  if (!cat) { console.warn(`skip ${f}: no category`); continue; }
  if (!CATS.includes(cat)) { console.warn(`skip ${f}: unknown category ${cat}`); continue; }
  knots.push({ id, cat });
}
const rank = (id) => { const i = ORDER.indexOf(id); return i < 0 ? 1000 : i; };
knots.sort((a, b) => CATS.indexOf(a.cat) - CATS.indexOf(b.cat) || rank(a.id) - rank(b.id) || a.id.localeCompare(b.id));
const varName = (id) => id.replace(/-(\w)/g, (_, c) => c.toUpperCase()).replace(/^(\d)/, '_$1');
let out = '// index.js: every knot in the archive, grouped by category. Generated by tools/gen-index.mjs; rerun it after adding a knot.\n';
let cur = null;
for (const k of knots) { if (k.cat !== cur) { cur = k.cat; out += `// ${cur}\n`; } out += `import ${varName(k.id)} from './${k.id}.js';\n`; }
out += '\nexport const KNOTS = [\n';
cur = null;
for (const k of knots) { if (k.cat !== cur) { cur = k.cat; out += `  // ${cur}\n`; } out += `  ${varName(k.id)},\n`; }
out += '];\nexport const KNOT_BY_ID = Object.fromEntries(KNOTS.map((k) => [k.id, k]));\n';
writeFileSync(resolve(dir, 'index.js'), out);
console.log(`index.js: ${knots.length} knots in ${new Set(knots.map((k) => k.cat)).size} categories`);
